    /**
     * 保留小数点后几位
     * @param str 被转换者
     * @param count 保留的位数
     * @return
     */
    public static String parsePointCount(String str, int count) {
        String result = str;
        int index = str.indexOf(".");
        if(index > 0 && str.length() > (index+count+1)){
            result = str.substring(0,index+count+1);
        }
        return result;
    }


